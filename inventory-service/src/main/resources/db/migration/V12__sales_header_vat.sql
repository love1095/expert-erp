-- Phase D1: sale order header, VAT per line, additional charges, order numbers (docs/phase-d-sales.md).

-- ---------------------------------------------------------------------------
-- Tax rates per organisation, named as in Cin7 (and Xero UK) so imported tax rules match by name
-- ---------------------------------------------------------------------------
CREATE TABLE tax_rates (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint        NOT NULL REFERENCES tenants (id),
    name      varchar(100)  NOT NULL,
    -- percent, e.g. 20.000
    rate      numeric(6,3)  NOT NULL CHECK (rate >= 0 AND rate <= 100),
    usage     varchar(10)   NOT NULL CHECK (usage IN ('SALE', 'PURCHASE')),
    active    boolean       NOT NULL DEFAULT true,
    CONSTRAINT uk_tax_rates_tenant_usage_name UNIQUE (tenant_id, usage, name)
);

-- UK rates for every existing organisation (new ones get them on first use)
INSERT INTO tax_rates (tenant_id, name, rate, usage)
SELECT t.id, v.name, v.rate, v.usage
  FROM tenants t
 CROSS JOIN (VALUES
       ('20% (VAT on Income)',            20, 'SALE'),
       ('5% (VAT on Income)',              5, 'SALE'),
       ('Zero Rated Income',               0, 'SALE'),
       ('Exempt Income',                   0, 'SALE'),
       ('No VAT',                          0, 'SALE'),
       ('20% (VAT on Expenses)',          20, 'PURCHASE'),
       ('5% (VAT on Expenses)',            5, 'PURCHASE'),
       ('Zero Rated Expenses',             0, 'PURCHASE'),
       ('Exempt Expenses',                 0, 'PURCHASE'),
       ('Reverse Charge Expenses (20%)',  20, 'PURCHASE'),
       ('No VAT',                          0, 'PURCHASE')
     ) AS v (name, rate, usage);

-- ---------------------------------------------------------------------------
-- Organisation settings
-- ---------------------------------------------------------------------------
ALTER TABLE tenants ADD COLUMN sale_order_prefix      varchar(10)  NOT NULL DEFAULT 'SO-';
-- The number the next sale order gets (set to Cin7's next number at cutover)
ALTER TABLE tenants ADD COLUMN next_sale_order_number bigint       NOT NULL DEFAULT 1;
-- Sales rep given to Shopify orders
ALTER TABLE tenants ADD COLUMN web_sales_rep          varchar(100) NOT NULL DEFAULT 'Web Sales';
-- Used when neither the product nor the customer has a sale tax rule
ALTER TABLE tenants ADD COLUMN default_sale_tax_rule  varchar(100) NOT NULL DEFAULT '20% (VAT on Income)';

-- ---------------------------------------------------------------------------
-- Sale order header
-- ---------------------------------------------------------------------------
ALTER TABLE sale_orders ADD COLUMN order_number       varchar(30);
UPDATE sale_orders SET order_number = 'SO-' || id;
ALTER TABLE sale_orders ALTER COLUMN order_number SET NOT NULL;
ALTER TABLE sale_orders ADD CONSTRAINT uk_sale_orders_tenant_number UNIQUE (tenant_id, order_number);
UPDATE tenants t SET next_sale_order_number = COALESCE((SELECT MAX(id) + 1 FROM sale_orders WHERE tenant_id = t.id), 1);

-- The customer's own reference (their PO number)
ALTER TABLE sale_orders ADD COLUMN customer_reference varchar(100);
ALTER TABLE sale_orders ADD COLUMN sales_rep          varchar(100);
ALTER TABLE sale_orders ADD COLUMN payment_term       varchar(100);
ALTER TABLE sale_orders ADD COLUMN ship_by            date;
ALTER TABLE sale_orders ADD COLUMN carrier            varchar(100);
ALTER TABLE sale_orders ADD COLUMN shipping_notes     text;
CREATE INDEX idx_sale_orders_tenant_rep ON sale_orders (tenant_id, sales_rep);

-- ---------------------------------------------------------------------------
-- Lines: discount and VAT, copied onto the line when the order is made
-- (older lines: no VAT recorded — tax_name empty, rate 0)
-- ---------------------------------------------------------------------------
ALTER TABLE sale_order_lines ADD COLUMN discount_percent numeric(5,2) NOT NULL DEFAULT 0
    CHECK (discount_percent >= 0 AND discount_percent <= 100);
ALTER TABLE sale_order_lines ADD COLUMN tax_name         varchar(100);
ALTER TABLE sale_order_lines ADD COLUMN tax_rate         numeric(6,3) NOT NULL DEFAULT 0;
-- Chosen by hand instead of the product / customer / default rule
ALTER TABLE sale_order_lines ADD COLUMN tax_overridden   boolean      NOT NULL DEFAULT false;

-- ---------------------------------------------------------------------------
-- Additional charges (carriage, delivery...): no product, no stock
-- ---------------------------------------------------------------------------
CREATE TABLE sale_order_charges (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_order_id    bigint        NOT NULL REFERENCES sale_orders (id) ON DELETE CASCADE,
    description      varchar(255)  NOT NULL,
    quantity         numeric(18,4) NOT NULL CHECK (quantity > 0),
    unit_price       numeric(18,4) NOT NULL CHECK (unit_price >= 0),
    discount_percent numeric(5,2)  NOT NULL DEFAULT 0 CHECK (discount_percent >= 0 AND discount_percent <= 100),
    tax_name         varchar(100),
    tax_rate         numeric(6,3)  NOT NULL DEFAULT 0,
    tax_overridden   boolean       NOT NULL DEFAULT false
);
CREATE INDEX idx_sale_order_charges_order ON sale_order_charges (sale_order_id);
