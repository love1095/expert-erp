-- Phase E1: the purchase order like Cin7 (docs/phase-e-purchasing.md). The PO is linked to the supplier record,
-- has its own number series, an "ordered" stage (Cin7's Authorise), supplier SKU, discount and purchase VAT per line,
-- and additional costs (freight, duty...).

-- Numbers: PO-19074 etc., continuing Cin7's series at cutover; existing orders keep the number they were shown with
ALTER TABLE tenants ADD COLUMN purchase_order_prefix      varchar(10)  NOT NULL DEFAULT 'PO-';
ALTER TABLE tenants ADD COLUMN next_purchase_order_number bigint       NOT NULL DEFAULT 1;
-- Used when neither the product nor the supplier has a purchase tax rule
ALTER TABLE tenants ADD COLUMN default_purchase_tax_rule  varchar(100) NOT NULL DEFAULT '20% (VAT on Expenses)';
UPDATE tenants t SET next_purchase_order_number = COALESCE((SELECT MAX(id) + 1 FROM purchase_orders p WHERE p.tenant_id = t.id), 1);

ALTER TABLE suppliers ADD COLUMN tax_rule varchar(100);

ALTER TABLE purchase_orders ADD COLUMN order_number       varchar(30);
UPDATE purchase_orders SET order_number = 'PO-' || id;
ALTER TABLE purchase_orders ALTER COLUMN order_number SET NOT NULL;
CREATE UNIQUE INDEX uk_purchase_orders_tenant_number ON purchase_orders (tenant_id, order_number);

ALTER TABLE purchase_orders ADD COLUMN supplier_id        bigint REFERENCES suppliers (id);
UPDATE purchase_orders p SET supplier_id = (
    SELECT MIN(s.id) FROM suppliers s WHERE s.tenant_id = p.tenant_id AND LOWER(s.name) = LOWER(p.supplier_name));
CREATE INDEX idx_purchase_orders_supplier ON purchase_orders (supplier_id);

ALTER TABLE purchase_orders ADD COLUMN supplier_reference varchar(100);
ALTER TABLE purchase_orders ADD COLUMN payment_term       varchar(100);
ALTER TABLE purchase_orders ADD COLUMN required_by        date;
-- When it was placed with the supplier (Cin7's Authorise); received orders were placed when created
ALTER TABLE purchase_orders ADD COLUMN ordered_at         timestamp(6);
UPDATE purchase_orders SET ordered_at = created_at WHERE status = 'RECEIVED';
ALTER TABLE purchase_orders ALTER COLUMN notes TYPE text;

ALTER TABLE purchase_orders DROP CONSTRAINT purchase_orders_status_check;
ALTER TABLE purchase_orders ADD CONSTRAINT purchase_orders_status_check
    CHECK (status IN ('DRAFT', 'ORDERED', 'RECEIVED', 'CANCELLED'));

-- Lines (older lines: no VAT recorded — tax_name empty, rate 0)
ALTER TABLE purchase_order_lines ADD COLUMN supplier_sku     varchar(100);
ALTER TABLE purchase_order_lines ADD COLUMN discount_percent numeric(5,2) NOT NULL DEFAULT 0
    CHECK (discount_percent >= 0 AND discount_percent <= 100);
ALTER TABLE purchase_order_lines ADD COLUMN tax_name         varchar(100);
ALTER TABLE purchase_order_lines ADD COLUMN tax_rate         numeric(6,3) NOT NULL DEFAULT 0;
ALTER TABLE purchase_order_lines ADD COLUMN tax_overridden   boolean      NOT NULL DEFAULT false;

-- Additional costs on the order (freight, duty, ...): an expense, not stock cost (decision 4)
CREATE TABLE purchase_order_costs (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id bigint        NOT NULL REFERENCES purchase_orders (id) ON DELETE CASCADE,
    description       varchar(255)  NOT NULL,
    reference         varchar(100),
    quantity          numeric(18,4) NOT NULL CHECK (quantity > 0),
    unit_price        numeric(18,4) NOT NULL CHECK (unit_price >= 0),
    discount_percent  numeric(5,2)  NOT NULL DEFAULT 0 CHECK (discount_percent >= 0 AND discount_percent <= 100),
    tax_name          varchar(100),
    tax_rate          numeric(6,3)  NOT NULL DEFAULT 0
);
CREATE INDEX idx_purchase_order_costs_order ON purchase_order_costs (purchase_order_id);
