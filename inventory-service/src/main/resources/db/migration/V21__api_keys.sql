-- API access per organisation, like Cin7 Core: every organisation (one subscription) has an Account ID, and its
-- admins create Application Keys for the systems that call the API. A request sends both, in the headers
-- api-auth-accountid and api-auth-applicationkey, and sees only that organisation's data.
ALTER TABLE tenants ADD COLUMN account_id uuid NOT NULL DEFAULT gen_random_uuid();
ALTER TABLE tenants ADD CONSTRAINT uq_tenants_account_id UNIQUE (account_id);

CREATE TABLE api_keys (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    bigint       NOT NULL,
    -- What the key is for, e.g. "Warehouse scanner", "Xero sync"
    name         varchar(100) NOT NULL,
    -- SHA-256 of the key (hex); the key itself is shown once, when it is made, and never stored
    key_hash     varchar(64)  NOT NULL UNIQUE,
    -- The key's first characters, so a key can be recognised in the list
    key_prefix   varchar(12)  NOT NULL,
    -- What the key may do: ADMIN, MANAGER or STAFF (never SUPER_ADMIN)
    role         varchar(20)  NOT NULL,
    created_by   varchar(100) NOT NULL,
    created_at   timestamp(6) NOT NULL,
    last_used_at timestamp(6),
    revoked_at   timestamp(6),
    revoked_by   varchar(100)
);
CREATE INDEX idx_api_keys_tenant ON api_keys (tenant_id);
