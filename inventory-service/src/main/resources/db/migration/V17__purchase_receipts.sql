-- Phase E2: goods receiving (docs/phase-e-purchasing.md). As in Cin7 (PO-19069: 18 ordered, 13 received → partially
-- received), stock arrives in receipts, several per order, each with its own date and quantities. More than ordered
-- is accepted and flagged (decision 2); a line can be closed short.

CREATE TABLE purchase_receipts (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         bigint       NOT NULL,
    purchase_order_id bigint       NOT NULL REFERENCES purchase_orders (id),
    warehouse_id      bigint       NOT NULL REFERENCES warehouses (id),
    received_on       date         NOT NULL,
    notes             text,
    -- A retried request with the same key is applied only once
    idempotency_key   varchar(100),
    created_by        varchar(255),
    created_at        timestamp(6) NOT NULL,
    CONSTRAINT uk_purchase_receipts_idempotency UNIQUE (tenant_id, idempotency_key)
);
CREATE INDEX idx_purchase_receipts_order ON purchase_receipts (purchase_order_id);

CREATE TABLE purchase_receipt_lines (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id             bigint        NOT NULL REFERENCES purchase_receipts (id) ON DELETE CASCADE,
    purchase_order_line_id bigint        NOT NULL REFERENCES purchase_order_lines (id),
    quantity               numeric(18,4) NOT NULL CHECK (quantity > 0),
    -- The part of this quantity above what was still outstanding (an over-delivery)
    over_quantity          numeric(18,4) NOT NULL DEFAULT 0 CHECK (over_quantity >= 0)
);
CREATE INDEX idx_purchase_receipt_lines_receipt ON purchase_receipt_lines (receipt_id);

-- Per order line: received so far, and the part closed short (not coming)
ALTER TABLE purchase_order_lines ADD COLUMN received_quantity     numeric(18,4) NOT NULL DEFAULT 0 CHECK (received_quantity >= 0);
ALTER TABLE purchase_order_lines ADD COLUMN closed_short_quantity numeric(18,4) NOT NULL DEFAULT 0 CHECK (closed_short_quantity >= 0);

-- Orders received before receipts existed were received in full
UPDATE purchase_order_lines l SET received_quantity = l.quantity
  FROM purchase_orders po WHERE po.id = l.purchase_order_id AND po.status = 'RECEIVED';
