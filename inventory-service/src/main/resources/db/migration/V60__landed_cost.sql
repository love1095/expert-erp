-- Phase P5: landed cost. With the setting on, freight and duty charged on a supplier bill are spread over the stock
-- that bill's lines received (by value or quantity) and added to its FIFO cost; off (the default) they stay an expense.

ALTER TABLE inventory_settings ADD COLUMN landed_cost varchar(10) NOT NULL DEFAULT 'OFF';   -- OFF, VALUE, QUANTITY

-- A bill's charge line made part of the stock cost (decided when the bill is issued)
ALTER TABLE invoice_items ADD COLUMN landed boolean NOT NULL DEFAULT false;

-- Where each landed charge went: the layers and amounts (to take it back if the bill is cancelled)
CREATE TABLE landed_costs (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        bigint         NOT NULL,
    invoice_item_id  bigint         NOT NULL REFERENCES invoice_items (id) ON DELETE CASCADE,
    layer_id         bigint         NOT NULL REFERENCES cost_layers (id) ON DELETE CASCADE,
    amount           numeric(18,4)  NOT NULL,
    created_at       timestamp(6)   NOT NULL DEFAULT now()
);
CREATE INDEX idx_landed_costs_item ON landed_costs (invoice_item_id);
