-- Phase L2: the Xero sync queue and the link from each ERP item to its Xero ID
CREATE TABLE xero_sync_items (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       bigint        NOT NULL,
    item_key        varchar(120)  NOT NULL,     -- CONTACT:CUSTOMER:5, DOC:12, PAY:40, JNL:…  (DOC / PAY / JNL as the CSV export's keys)
    kind            varchar(20)   NOT NULL,     -- CONTACT, INVOICE, BILL, CREDIT_NOTE, SUPPLIER_CREDIT, PAYMENT, JOURNAL, ALLOCATION
    label           varchar(255),               -- what a person sees: "Invoice INV-118661 — AE Yates Ltd"
    depends_on      varchar(120),               -- sent only after this item (an invoice after its contact)
    xero_id         varchar(64),                -- the ContactID / InvoiceID / PaymentID… once sent
    status          varchar(10)   NOT NULL DEFAULT 'PENDING',   -- PENDING, SENT, FAILED
    attempts        int           NOT NULL DEFAULT 0,
    last_error      text,
    next_attempt_at timestamp(6)  NOT NULL DEFAULT now(),
    created_at      timestamp(6)  NOT NULL DEFAULT now(),
    sent_at         timestamp(6),
    updated_at      timestamp(6)  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_xero_sync_items_key ON xero_sync_items (tenant_id, item_key);
CREATE INDEX idx_xero_sync_items_due ON xero_sync_items (tenant_id, status, next_attempt_at);
