-- Phase H5: export to the accounting package (Xero), CSV files first.

-- Account mapping like Cin7 Core's (Reference Books -> Account mapping), one row per organisation
CREATE TABLE accounting_settings (
    tenant_id                bigint PRIMARY KEY,
    -- Nothing dated before this day is exported: the package already has it (Cin7 sent it)
    export_start_date        date,
    revenue_account          varchar(20),
    inventory_account        varchar(20),
    cogs_account             varchar(20),
    discrepancy_account      varchar(20),
    purchase_charges_account varchar(20),
    customer_credit_account  varchar(20),
    supplier_deposits_account varchar(20),
    updated_at               timestamp,
    updated_by               varchar(100)
);

-- One export: the files made, kept to download again
CREATE TABLE accounting_export_batches (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      bigint       NOT NULL,
    package        varchar(20)  NOT NULL DEFAULT 'XERO_CSV',
    created_at     timestamp    NOT NULL DEFAULT now(),
    created_by     varchar(100) NOT NULL,
    invoices       int          NOT NULL DEFAULT 0,
    credit_notes   int          NOT NULL DEFAULT 0,
    bills          int          NOT NULL DEFAULT 0,
    supplier_credits int        NOT NULL DEFAULT 0,
    journals       int          NOT NULL DEFAULT 0,
    payments       int          NOT NULL DEFAULT 0,
    file           bytea        NOT NULL,
    undone_at      timestamp,
    undone_by      varchar(100)
);
CREATE INDEX idx_accounting_export_batches_tenant ON accounting_export_batches (tenant_id, created_at DESC);

-- What has been exported: one row per document / journal / payment, never twice (undo removes the batch's rows)
CREATE TABLE accounting_exported (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint       NOT NULL,
    batch_id  bigint       NOT NULL REFERENCES accounting_export_batches (id),
    doc_key   varchar(120) NOT NULL,
    doc_date  date         NOT NULL,
    amount    numeric(18,2),
    CONSTRAINT uk_accounting_exported UNIQUE (tenant_id, doc_key)
);
CREATE INDEX idx_accounting_exported_batch ON accounting_exported (batch_id);
