-- Phase H1: sales ledger. Payment accounts like Cin7's (from the Xero chart), payments with their date, account and
-- reference, customer credit (overpayments and prepayments), voided payments kept in their own history.

CREATE TABLE payment_accounts (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  bigint       NOT NULL,
    code       varchar(20)  NOT NULL,
    name       varchar(150) NOT NULL,
    kind       varchar(20)  NOT NULL DEFAULT 'BANK' CHECK (kind IN ('BANK', 'CARD', 'CASH', 'PAYPAL', 'SHOPIFY', 'OTHER')),
    active     boolean      NOT NULL DEFAULT true,
    is_default boolean      NOT NULL DEFAULT false,
    UNIQUE (tenant_id, code)
);

ALTER TABLE payments DROP CONSTRAINT IF EXISTS payments_method_check;
ALTER TABLE payments ADD CONSTRAINT payments_method_check
    CHECK (method IN ('CASH', 'BANK', 'STRIPE', 'CARD', 'PAYPAL', 'CREDIT_NOTE', 'CUSTOMER_CREDIT', 'SHOPIFY'));
ALTER TABLE payments ADD COLUMN payment_account_id bigint REFERENCES payment_accounts (id);

-- Money a customer paid that is not on an invoice yet: an overpayment, or paid before the invoice
CREATE TABLE customer_credits (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          bigint        NOT NULL,
    customer_id        bigint        NOT NULL REFERENCES customers (id),
    amount             numeric(18,2) NOT NULL CHECK (amount > 0),
    received_on        date          NOT NULL,
    method             varchar(20)   NOT NULL,
    payment_account_id bigint        REFERENCES payment_accounts (id),
    reference          varchar(100),
    -- The invoice that was overpaid, when it came from one
    source_invoice_id  bigint        REFERENCES invoices (id),
    note               varchar(255),
    created_by         varchar(100)  NOT NULL,
    created_at         timestamp     NOT NULL DEFAULT now()
);
CREATE INDEX idx_customer_credits_customer ON customer_credits (tenant_id, customer_id);

-- An invoice paid with customer credit: the credit it came from
ALTER TABLE payments ADD COLUMN customer_credit_id bigint REFERENCES customer_credits (id);
CREATE INDEX idx_payments_customer_credit ON payments (customer_credit_id);

-- Payments voided by a manager: out of every total, kept here with who, when and why
CREATE TABLE voided_payments (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          bigint        NOT NULL,
    payment_id         bigint        NOT NULL,
    invoice_id         bigint        NOT NULL REFERENCES invoices (id),
    amount             numeric(18,2) NOT NULL,
    method             varchar(20)   NOT NULL,
    paid_at            timestamp     NOT NULL,
    payment_account_id bigint        REFERENCES payment_accounts (id),
    reference          varchar(100),
    credit_note_id     bigint,
    customer_credit_id bigint,
    reason             varchar(255)  NOT NULL,
    voided_by          varchar(100)  NOT NULL,
    voided_at          timestamp     NOT NULL DEFAULT now()
);
CREATE INDEX idx_voided_payments_invoice ON voided_payments (invoice_id);
