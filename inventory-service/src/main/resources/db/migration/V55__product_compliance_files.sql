-- Phase P1: safety compliance per SKU (never taken from another product of the family), and P4: product files
-- (images, datasheets, declarations of conformity, certificates) kept in the database like the other documents

CREATE TABLE product_compliance (
    product_id          bigint        PRIMARY KEY REFERENCES products (id) ON DELETE CASCADE,
    tenant_id           bigint        NOT NULL,
    standards           varchar(500),                 -- e.g. EN 388:2016+A1:2018; EN ISO 21420:2020
    ce_marked           boolean       NOT NULL DEFAULT false,
    ukca_marked         boolean       NOT NULL DEFAULT false,
    protection_class    varchar(100),                 -- e.g. Category II, S3 SRC, Class 2
    certificate_number  varchar(100),
    certificate_issuer  varchar(150),                 -- the notified / approved body
    certificate_expiry  date,
    notes               varchar(1000),
    updated_at          timestamp(6),
    updated_by          varchar(100)
);
CREATE INDEX idx_product_compliance_expiry ON product_compliance (tenant_id, certificate_expiry);

CREATE TABLE product_files (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     bigint         NOT NULL,
    product_id    bigint         NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    kind          varchar(20)    NOT NULL,            -- IMAGE, DATASHEET, DECLARATION, CERTIFICATE, OTHER
    file_name     varchar(255)   NOT NULL,
    content_type  varchar(100)   NOT NULL,
    size_bytes    int            NOT NULL,
    content       bytea          NOT NULL,
    position      int            NOT NULL DEFAULT 0,  -- images: the first is the main image
    created_at    timestamp(6)   NOT NULL DEFAULT now(),
    created_by    varchar(100)
);
CREATE INDEX idx_product_files_product ON product_files (tenant_id, product_id, kind, position);
