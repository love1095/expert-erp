-- Sale order lifecycle: separate order status from fulfilment status,
-- partial fulfilment, cancellation of remaining quantities, customer returns,
-- and explicit audit actors.

-- ---------------------------------------------------------------------------
-- sale_orders: DRAFT/FULFILLED/CANCELLED -> DRAFT/CONFIRMED/COMPLETED/CANCELLED
--              + fulfilment_status UNFULFILLED/PARTIALLY_FULFILLED/FULFILLED
-- ---------------------------------------------------------------------------
ALTER TABLE sale_orders DROP CONSTRAINT IF EXISTS sale_orders_status_check;

ALTER TABLE sale_orders ADD COLUMN fulfilment_status varchar(255) NOT NULL DEFAULT 'UNFULFILLED';
ALTER TABLE sale_orders ADD COLUMN confirmed_at timestamp(6);
ALTER TABLE sale_orders ADD COLUMN cancelled_at timestamp(6);

UPDATE sale_orders
   SET status = 'COMPLETED',
       fulfilment_status = 'FULFILLED',
       confirmed_at = COALESCE(fulfilled_at, created_at)
 WHERE status = 'FULFILLED';

UPDATE sale_orders SET cancelled_at = created_at WHERE status = 'CANCELLED';

ALTER TABLE sale_orders ADD CONSTRAINT sale_orders_status_check
    CHECK (status IN ('DRAFT', 'CONFIRMED', 'COMPLETED', 'CANCELLED'));
ALTER TABLE sale_orders ADD CONSTRAINT sale_orders_fulfilment_status_check
    CHECK (fulfilment_status IN ('UNFULFILLED', 'PARTIALLY_FULFILLED', 'FULFILLED'));

-- ---------------------------------------------------------------------------
-- sale_order_lines: per-line progress
-- ---------------------------------------------------------------------------
ALTER TABLE sale_order_lines ADD COLUMN fulfilled_quantity numeric(18,4) NOT NULL DEFAULT 0;
ALTER TABLE sale_order_lines ADD COLUMN cancelled_quantity numeric(18,4) NOT NULL DEFAULT 0;
ALTER TABLE sale_order_lines ADD COLUMN returned_quantity  numeric(18,4) NOT NULL DEFAULT 0;

UPDATE sale_order_lines l
   SET fulfilled_quantity = l.quantity
  FROM sale_orders so
 WHERE so.id = l.sale_order_id AND so.fulfilment_status = 'FULFILLED';

UPDATE sale_order_lines l
   SET cancelled_quantity = l.quantity
  FROM sale_orders so
 WHERE so.id = l.sale_order_id AND so.status = 'CANCELLED';

ALTER TABLE sale_order_lines ADD CONSTRAINT sale_order_lines_progress_check
    CHECK (fulfilled_quantity >= 0
       AND cancelled_quantity >= 0
       AND fulfilled_quantity + cancelled_quantity <= quantity
       AND returned_quantity >= 0
       AND returned_quantity <= fulfilled_quantity);

CREATE INDEX idx_sol_sale_order ON sale_order_lines (sale_order_id);

-- ---------------------------------------------------------------------------
-- fulfilments: one row per shipment; idempotency_key makes retries safe
-- ---------------------------------------------------------------------------
CREATE TABLE fulfilments (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       bigint       NOT NULL,
    sale_order_id   bigint       NOT NULL REFERENCES sale_orders (id),
    idempotency_key varchar(255),
    notes           varchar(255),
    created_by      varchar(255),
    created_at      timestamp(6) NOT NULL,
    CONSTRAINT uk_fulfilments_idempotency UNIQUE (tenant_id, idempotency_key)
);
CREATE INDEX idx_fulfilments_sale_order ON fulfilments (sale_order_id);

CREATE TABLE fulfilment_lines (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fulfilment_id      bigint        NOT NULL REFERENCES fulfilments (id),
    sale_order_line_id bigint        NOT NULL REFERENCES sale_order_lines (id),
    quantity           numeric(18,4) NOT NULL CHECK (quantity > 0)
);
CREATE INDEX idx_fulfilment_lines_fulfilment ON fulfilment_lines (fulfilment_id);

-- ---------------------------------------------------------------------------
-- sale_returns: goods coming back from the customer
-- ---------------------------------------------------------------------------
CREATE TABLE sale_returns (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       bigint       NOT NULL,
    sale_order_id   bigint       NOT NULL REFERENCES sale_orders (id),
    warehouse_id    bigint       NOT NULL REFERENCES warehouses (id),
    idempotency_key varchar(255),
    reason          varchar(255),
    created_by      varchar(255),
    created_at      timestamp(6) NOT NULL,
    CONSTRAINT uk_sale_returns_idempotency UNIQUE (tenant_id, idempotency_key)
);
CREATE INDEX idx_sale_returns_sale_order ON sale_returns (sale_order_id);

CREATE TABLE sale_return_lines (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_return_id     bigint        NOT NULL REFERENCES sale_returns (id),
    sale_order_line_id bigint        NOT NULL REFERENCES sale_order_lines (id),
    quantity           numeric(18,4) NOT NULL CHECK (quantity > 0),
    restock            boolean       NOT NULL
);
CREATE INDEX idx_sale_return_lines_return ON sale_return_lines (sale_return_id);

-- ---------------------------------------------------------------------------
-- stock_movements: new SALE_RETURN_IN type and SALE_RETURN reference
-- ---------------------------------------------------------------------------
ALTER TABLE stock_movements DROP CONSTRAINT IF EXISTS stock_movements_type_check;
ALTER TABLE stock_movements ADD CONSTRAINT stock_movements_type_check
    CHECK (type IN ('PURCHASE_IN', 'SALE_OUT', 'ADJUSTMENT_IN', 'ADJUSTMENT_OUT',
                    'TRANSFER_IN', 'TRANSFER_OUT', 'SALE_RETURN_IN'));

ALTER TABLE stock_movements DROP CONSTRAINT IF EXISTS stock_movements_reference_type_check;
ALTER TABLE stock_movements ADD CONSTRAINT stock_movements_reference_type_check
    CHECK (reference_type IN ('PURCHASE_ORDER', 'SALE_ORDER', 'SALE_RETURN',
                              'TRANSFER', 'ADJUSTMENT', 'MANUAL'));

-- ---------------------------------------------------------------------------
-- audit_log: who performed the action (user, system job, or integration)
-- ---------------------------------------------------------------------------
ALTER TABLE audit_log ADD COLUMN actor_type varchar(255) NOT NULL DEFAULT 'USER';
ALTER TABLE audit_log ADD COLUMN actor_id   varchar(255);

UPDATE audit_log SET actor_type = 'SYSTEM' WHERE username IS NULL OR username = 'system';
UPDATE audit_log SET actor_id = username;

ALTER TABLE audit_log ADD CONSTRAINT audit_log_actor_type_check
    CHECK (actor_type IN ('USER', 'SYSTEM', 'INTEGRATION'));
