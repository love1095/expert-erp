-- Phase H2: purchase ledger. Supplier credit notes (optionally sending goods back: PURCHASE_RETURN_OUT at the cost they
-- came in at), supplier credit (deposits and overpaid bills, Cin7's "Use supplier deposit"), supplier ledger.

ALTER TABLE stock_movements DROP CONSTRAINT IF EXISTS stock_movements_type_check;
ALTER TABLE stock_movements ADD CONSTRAINT stock_movements_type_check
    CHECK (type IN ('PURCHASE_IN', 'SALE_OUT', 'ADJUSTMENT_IN', 'ADJUSTMENT_OUT',
                    'TRANSFER_IN', 'TRANSFER_OUT', 'SALE_RETURN_IN', 'PURCHASE_RETURN_OUT'));
ALTER TABLE stock_movements DROP CONSTRAINT IF EXISTS stock_movements_reference_type_check;
ALTER TABLE stock_movements ADD CONSTRAINT stock_movements_reference_type_check
    CHECK (reference_type IN ('PURCHASE_ORDER', 'SALE_ORDER', 'SALE_RETURN', 'PURCHASE_RETURN',
                              'TRANSFER', 'ADJUSTMENT', 'MANUAL', 'STOCK_IMPORT'));

-- Money paid to a supplier that is not on a bill yet: a deposit, or the rest of an overpaid bill
CREATE TABLE supplier_credits (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          bigint        NOT NULL,
    supplier_id        bigint        NOT NULL REFERENCES suppliers (id),
    amount             numeric(18,2) NOT NULL CHECK (amount > 0),
    paid_on            date          NOT NULL,
    method             varchar(20)   NOT NULL,
    payment_account_id bigint        REFERENCES payment_accounts (id),
    reference          varchar(100),
    source_invoice_id  bigint        REFERENCES invoices (id),
    purchase_order_id  bigint        REFERENCES purchase_orders (id),
    note               varchar(255),
    created_by         varchar(100)  NOT NULL,
    created_at         timestamp     NOT NULL DEFAULT now()
);
CREATE INDEX idx_supplier_credits_supplier ON supplier_credits (tenant_id, supplier_id);

ALTER TABLE payments DROP CONSTRAINT IF EXISTS payments_method_check;
ALTER TABLE payments ADD CONSTRAINT payments_method_check
    CHECK (method IN ('CASH', 'BANK', 'STRIPE', 'CARD', 'PAYPAL', 'CREDIT_NOTE', 'CUSTOMER_CREDIT', 'SUPPLIER_CREDIT', 'SHOPIFY'));
ALTER TABLE payments ADD COLUMN supplier_credit_id bigint REFERENCES supplier_credits (id);
CREATE INDEX idx_payments_supplier_credit ON payments (supplier_credit_id);
ALTER TABLE voided_payments ADD COLUMN supplier_credit_id bigint;
