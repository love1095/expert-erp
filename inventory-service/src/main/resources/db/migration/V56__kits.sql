-- Phase P2: kits and bundles. A KIT product holds no stock of its own: it is made of components, its stock is what
-- the components can make, and selling it takes the components (at their FIFO cost).

CREATE TABLE kit_components (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     bigint         NOT NULL,
    kit_id        bigint         NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    component_id  bigint         NOT NULL REFERENCES products (id),
    quantity      numeric(18,4)  NOT NULL CHECK (quantity > 0),     -- of the component in one kit
    CONSTRAINT uk_kit_component UNIQUE (kit_id, component_id)
);
CREATE INDEX idx_kit_components_kit ON kit_components (tenant_id, kit_id);
CREATE INDEX idx_kit_components_component ON kit_components (tenant_id, component_id);

-- A kit line on a pick list is picked as its components: how many of the component make one kit (1 for other lines)
ALTER TABLE pick_list_lines ADD COLUMN per_kit numeric(18,4) NOT NULL DEFAULT 1;

ALTER TABLE products DROP CONSTRAINT products_product_type_check;
ALTER TABLE products ADD CONSTRAINT products_product_type_check CHECK (product_type IN ('STOCK', 'SERVICE', 'KIT'));
