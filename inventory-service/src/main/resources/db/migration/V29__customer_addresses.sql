-- Orders made before printed the customer's address: they keep it, as billing and shipping
UPDATE sale_orders so SET billing_line1 = a.line1, billing_line2 = a.line2,
                          shipping_line1 = a.line1, shipping_line2 = a.line2
FROM customer_addresses a
WHERE a.customer_id = so.customer_id AND a.default_for_type;
