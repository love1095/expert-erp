-- Phase G4: customers' address book (Cin7's Addresses tab) and billing / shipping addresses on sale orders.

CREATE TABLE customer_addresses (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        bigint       NOT NULL,
    customer_id      bigint       NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    line1            varchar(255),
    line2            varchar(255),
    city             varchar(100),
    state            varchar(100),
    postcode         varchar(30),
    country          varchar(100),
    type             varchar(20)  NOT NULL DEFAULT 'BILLING' CHECK (type IN ('BILLING', 'BUSINESS', 'SHIPPING')),
    default_for_type boolean      NOT NULL DEFAULT false
);
CREATE INDEX idx_customer_addresses_customer ON customer_addresses (customer_id);

-- The old one-text address becomes the default billing address: its first line is line 1, the rest line 2
-- (lines were split by new lines, or else by commas)
INSERT INTO customer_addresses (tenant_id, customer_id, line1, line2, type, default_for_type)
SELECT c.tenant_id, c.id,
       left(trim(split_part(x.a, x.sep, 1)), 255),
       NULLIF(left(trim(both ', ' from regexp_replace(substr(x.a, length(split_part(x.a, x.sep, 1)) + 2), '\s*[,\n]\s*', ', ', 'g')), 255), ''),
       'BILLING', true
FROM customers c
CROSS JOIN LATERAL (SELECT replace(trim(c.address), E'\r', '') AS a,
                           CASE WHEN position(E'\n' IN c.address) > 0 THEN E'\n' ELSE ',' END AS sep) x
WHERE c.address IS NOT NULL AND trim(c.address) <> '';

ALTER TABLE customers DROP COLUMN address;

ALTER TABLE sale_orders ADD COLUMN billing_line1    varchar(255);
