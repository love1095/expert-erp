-- Phase L4: payments entered in Xero, pulled back and recorded against the ERP's invoices and bills
CREATE TABLE xero_pulled_payments (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        bigint        NOT NULL,
    xero_payment_id  varchar(64)   NOT NULL,
    xero_status      varchar(12),                 -- AUTHORISED / DELETED in Xero
    doc_key          varchar(120),                -- DOC:id of the ERP document it was for
    erp_payment_id   bigint,                      -- the payment recorded here
    amount           numeric(18,2),
    paid_on          date,
    status           varchar(12)   NOT NULL,      -- RECORDED, VOIDED, UNMATCHED, ERROR
    message          text,
    pulled_at        timestamp(6)  NOT NULL DEFAULT now(),
    updated_at       timestamp(6)  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_xero_pulled_payments ON xero_pulled_payments (tenant_id, xero_payment_id);

ALTER TABLE xero_connections ADD COLUMN payments_pulled_at timestamp(6);   -- Xero's If-Modified-Since for the next pull
ALTER TABLE xero_connections ADD COLUMN pull_requested_at timestamp(6);    -- a Xero webhook asked for a pull
