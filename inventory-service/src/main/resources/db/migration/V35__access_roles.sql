-- Phase I1: roles with ticked permissions, like Cin7 Core's Settings -> Users & Roles.
CREATE TABLE access_roles (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   bigint       NOT NULL,
    name        varchar(60)  NOT NULL,
    -- Comma-separated permission names (security.Permission)
    permissions text         NOT NULL DEFAULT '',
    created_at  timestamp    NOT NULL DEFAULT now(),
    updated_at  timestamp
);
CREATE UNIQUE INDEX uk_access_roles_name ON access_roles (tenant_id, lower(name));

-- A user's role; none = the defaults of the user's old role (Manager / Staff). Admins have every permission.
ALTER TABLE users ADD COLUMN access_role_id bigint REFERENCES access_roles (id);
