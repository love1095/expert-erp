-- Phase J: Cin7's sale / purchase task CSV import, with its Logs tab (one row per file imported)
CREATE TABLE data_import_logs (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   bigint       NOT NULL,
    kind        varchar(20)  NOT NULL,          -- SALES / PURCHASES
    file_name   varchar(255),
    options     varchar(255),
    documents   int          NOT NULL DEFAULT 0,
    total       numeric(18,2) NOT NULL DEFAULT 0,
    created_at  timestamp    NOT NULL DEFAULT now(),
    created_by  varchar(100) NOT NULL
);
CREATE INDEX idx_data_import_logs_tenant ON data_import_logs (tenant_id, created_at DESC);
