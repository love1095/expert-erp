-- Phase I4: named document templates per document type, like Cin7 Core's Document and email templates
-- (Expert Safety has e.g. "Invoice - Account Client", "Invoice - Cash Sale", "Delivery Note"). Cin7 takes Word
-- mail-merge files; here a template is a set of safe layout settings on the ERP's own PDF layout.
CREATE TABLE document_templates (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        bigint       NOT NULL,
    doc_type         varchar(20)  NOT NULL CHECK (doc_type IN ('QUOTE', 'SALES_ORDER', 'INVOICE', 'CREDIT_NOTE', 'PURCHASE_ORDER')),
    name             varchar(80)  NOT NULL,
    is_default       boolean      NOT NULL DEFAULT false,
    -- Printed title instead of the usual one ("Delivery note", "Pro forma invoice"); null = usual
    title            varchar(60),
    accent_color     varchar(7)   NOT NULL DEFAULT '#d42020' CHECK (accent_color ~ '^#[0-9a-fA-F]{6}$'),
    show_logo        boolean      NOT NULL DEFAULT true,
    -- No prices: a delivery note or pick list (no prices, totals, VAT or payment)
    show_prices      boolean      NOT NULL DEFAULT true,
    show_sku         boolean      NOT NULL DEFAULT true,
    show_discount    boolean      NOT NULL DEFAULT true,
    show_vat_summary boolean      NOT NULL DEFAULT true,
    intro_text       varchar(2000),
    -- Replaces the usual payment box (bank details / terms) and the company footer when set
    payment_text     varchar(2000),
    footer_text      varchar(2000),
    email_subject    varchar(200),
    created_at       timestamp    NOT NULL DEFAULT now(),
    updated_at       timestamp
);
CREATE UNIQUE INDEX uk_document_templates_name ON document_templates (tenant_id, doc_type, lower(name));
CREATE UNIQUE INDEX uk_document_templates_default ON document_templates (tenant_id, doc_type) WHERE is_default;
