-- Phase P3: units of measure. A product's extra units (pair, box of 100, carton) with how many base units each holds;
-- an order line is in the unit it was sold or bought in, stock and FIFO stay in the base unit.

CREATE TABLE product_units (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   bigint         NOT NULL,
    product_id  bigint         NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    name        varchar(50)    NOT NULL,
    factor      numeric(18,4)  NOT NULL CHECK (factor > 0),   -- base units in one of this unit
    barcode     varchar(100),
    sell_price  numeric(18,4),                               -- empty: the base price × factor
    buy_price   numeric(18,4)                                -- empty: the base cost × factor
);
CREATE UNIQUE INDEX uk_product_units_name ON product_units (product_id, lower(name));
CREATE INDEX idx_product_units_tenant ON product_units (tenant_id, product_id);

ALTER TABLE sale_order_lines ADD COLUMN unit_name varchar(50);
ALTER TABLE sale_order_lines ADD COLUMN unit_factor numeric(18,4) NOT NULL DEFAULT 1;
ALTER TABLE purchase_order_lines ADD COLUMN unit_name varchar(50);
ALTER TABLE purchase_order_lines ADD COLUMN unit_factor numeric(18,4) NOT NULL DEFAULT 1;
ALTER TABLE invoice_items ADD COLUMN unit_name varchar(50);
