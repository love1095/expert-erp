-- Phase E5: FIFO cost layers (docs/business-rules.md section 2, docs/phase-e-purchasing.md E5).
-- Every stock-in opens a layer (what is left of it, at what unit cost); every stock-out takes from the oldest layers
-- first and records what it took: that is the cost of goods sold of a shipment. A supplier bill priced differently
-- from the PO corrects the layer and the cost already taken from it through cost adjustments, never by editing history.
-- Layers are bookkeeping only: quantities still come from stock_movements, and layers can be rebuilt from them.

-- The order line a movement belongs to: the PO line for a receipt, the sale order line for a shipment or a return
ALTER TABLE stock_movements ADD COLUMN source_line_id bigint;

-- Movements made before this column existed, matched on the order number and the product (first line wins)
UPDATE stock_movements m SET source_line_id = (
    SELECT MIN(l.id) FROM purchase_order_lines l JOIN purchase_orders po ON po.id = l.purchase_order_id
     WHERE po.order_number = m.reference_id AND l.product_id = m.product_id AND po.tenant_id = m.tenant_id)
 WHERE m.type = 'PURCHASE_IN' AND m.reference_type = 'PURCHASE_ORDER';
UPDATE stock_movements m SET source_line_id = (
    SELECT MIN(l.id) FROM sale_order_lines l JOIN sale_orders so ON so.id = l.sale_order_id
     WHERE 'SO-' || so.id = m.reference_id AND l.product_id = m.product_id AND so.tenant_id = m.tenant_id)
 WHERE m.type = 'SALE_OUT' AND m.reference_type = 'SALE_ORDER';
UPDATE stock_movements m SET source_line_id = (
    SELECT MIN(rl.sale_order_line_id) FROM sale_return_lines rl
      JOIN sale_order_lines l ON l.id = rl.sale_order_line_id
     WHERE 'RET-' || rl.sale_return_id = m.reference_id AND l.product_id = m.product_id)
 WHERE m.type = 'SALE_RETURN_IN' AND m.reference_type = 'SALE_RETURN';

CREATE TABLE cost_layers (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        bigint        NOT NULL,
    product_id       bigint        NOT NULL REFERENCES products (id),
    warehouse_id     bigint        NOT NULL REFERENCES warehouses (id),
    -- The stock-in that opened it
    movement_id      bigint        NOT NULL REFERENCES stock_movements (id),
    -- FIFO order: when the stock first came in (a transfer keeps the date of the layer it came from)
    received_at      timestamp(6)  NOT NULL,
    quantity         numeric(18,4) NOT NULL CHECK (quantity > 0),
    remaining        numeric(18,4) NOT NULL CHECK (remaining >= 0),
    -- Current cost of one unit (after bill corrections), and the cost it came in at
    unit_cost        numeric(18,6) NOT NULL,
    original_unit_cost numeric(18,6) NOT NULL,
    -- Receipts: the PO line, and how many of its units a supplier bill has priced so far
    purchase_order_line_id bigint,
    billed_quantity  numeric(18,4) NOT NULL DEFAULT 0 CHECK (billed_quantity >= 0),
    -- Transfers: the layer in the other warehouse it came from
    source_layer_id  bigint REFERENCES cost_layers (id),
    created_at       timestamp(6)  NOT NULL
);
CREATE INDEX idx_cost_layers_open ON cost_layers (product_id, warehouse_id, received_at, id) WHERE remaining > 0;
CREATE INDEX idx_cost_layers_movement ON cost_layers (movement_id);
CREATE INDEX idx_cost_layers_po_line ON cost_layers (purchase_order_line_id) WHERE purchase_order_line_id IS NOT NULL;
CREATE INDEX idx_cost_layers_tenant ON cost_layers (tenant_id);

-- What a stock-out took from a layer, at the unit cost of that moment
CREATE TABLE cost_consumptions (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      bigint        NOT NULL,
    layer_id       bigint        NOT NULL REFERENCES cost_layers (id),
    movement_id    bigint        NOT NULL REFERENCES stock_movements (id),
    quantity       numeric(18,4) NOT NULL CHECK (quantity > 0),
    unit_cost      numeric(18,6) NOT NULL,
    -- Transfers: the layer this quantity opened in the other warehouse
    child_layer_id bigint REFERENCES cost_layers (id),
    created_at     timestamp(6)  NOT NULL
);
CREATE INDEX idx_cost_consumptions_layer ON cost_consumptions (layer_id);
CREATE INDEX idx_cost_consumptions_movement ON cost_consumptions (movement_id);
CREATE INDEX idx_cost_consumptions_tenant ON cost_consumptions (tenant_id);

-- A correction of a layer's cost (supplier bill at another price than the PO, or its cancellation): the part still
-- in stock (movement_id empty) and the part already gone, per stock-out (movement_id = the shipment or write-off).
CREATE TABLE cost_adjustments (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        bigint        NOT NULL,
    layer_id         bigint        NOT NULL REFERENCES cost_layers (id),
    movement_id      bigint REFERENCES stock_movements (id),
    invoice_item_id  bigint REFERENCES invoice_items (id),
    -- Units of the layer the bill priced (only on the row made at the layer the bill was matched to)
    billed_quantity  numeric(18,4),
    amount           numeric(18,4) NOT NULL,
    reason           varchar(255)  NOT NULL,
    created_at       timestamp(6)  NOT NULL
);
CREATE INDEX idx_cost_adjustments_layer ON cost_adjustments (layer_id);
CREATE INDEX idx_cost_adjustments_movement ON cost_adjustments (movement_id) WHERE movement_id IS NOT NULL;
CREATE INDEX idx_cost_adjustments_item ON cost_adjustments (invoice_item_id) WHERE invoice_item_id IS NOT NULL;
CREATE INDEX idx_cost_adjustments_tenant ON cost_adjustments (tenant_id);

-- Bill lines: how many of their units have been matched to received layers (the rest waits for the goods)
ALTER TABLE invoice_items ADD COLUMN cost_matched_quantity numeric(18,4) NOT NULL DEFAULT 0;

