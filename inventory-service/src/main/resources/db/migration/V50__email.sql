-- Phase M: e-mail (spec §7) — the organisation's mail settings, editable e-mail templates per document type, and
-- every e-mail made (the outbox; in fake mode stored, not sent), which is also each document's "sent" log

CREATE TABLE mail_settings (
    tenant_id                bigint        PRIMARY KEY,
    from_name                varchar(255),
    from_address             varchar(255),
    reply_to                 varchar(255),
    smtp_host                varchar(255),
    smtp_port                int,
    smtp_username            varchar(255),
    smtp_password_encrypted  text,
    smtp_starttls            boolean       NOT NULL DEFAULT true,
    updated_at               timestamp(6),
    updated_by               varchar(100)
);

CREATE TABLE mail_templates (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   bigint        NOT NULL,
    doc_type    varchar(30)   NOT NULL,   -- QUOTE, SALES_ORDER, INVOICE, CREDIT_NOTE, STATEMENT, REMINDER_1..3, PURCHASE_ORDER, TRACKING
    subject     varchar(500)  NOT NULL,
    body        text          NOT NULL,
    updated_at  timestamp(6)  NOT NULL DEFAULT now(),
    updated_by  varchar(100)
);
CREATE UNIQUE INDEX uk_mail_templates_type ON mail_templates (tenant_id, doc_type);

CREATE TABLE mail_outbox (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        bigint        NOT NULL,
    doc_type         varchar(30)   NOT NULL,
    doc_key          varchar(60)   NOT NULL,      -- SO:12, DOC:40, PO:7, CUST:5 (statements, reminders)
    doc_label        varchar(255),                -- "Invoice INV-118661"
    to_address       varchar(500)  NOT NULL,
    cc_address       varchar(500),
    subject          varchar(500)  NOT NULL,
    body             text          NOT NULL,
    attachment_name  varchar(255),
    attachment       bytea,
    mode             varchar(10)   NOT NULL,      -- fake (kept here) or live (sent by SMTP)
    status           varchar(10)   NOT NULL,      -- KEPT (fake), SENT, FAILED
    error            text,
    created_at       timestamp(6)  NOT NULL DEFAULT now(),
    created_by       varchar(100)
);
CREATE INDEX idx_mail_outbox_tenant ON mail_outbox (tenant_id, created_at DESC);
CREATE INDEX idx_mail_outbox_doc ON mail_outbox (tenant_id, doc_key);
