-- Phase K3: bank statements and reconciliation, like Xero's (Accounting → Bank accounts → Reconcile)

-- Spend money / receive money / transfers made in the ERP (Xero's bank transactions); posted to the ledger as BT:id
CREATE TABLE bank_transactions (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       bigint        NOT NULL,
    kind            varchar(10)   NOT NULL,          -- SPEND, RECEIVE, TRANSFER
    txn_date        date          NOT NULL,
    account_code    varchar(10)   NOT NULL,          -- the bank account (transfers: from)
    to_account_code varchar(10),                     -- transfers: to
    contact         varchar(255),
    reference       varchar(255),
    total           numeric(18,2) NOT NULL,          -- always positive
    status          varchar(10)   NOT NULL DEFAULT 'ACTIVE',   -- ACTIVE, VOIDED
    created_at      timestamp     NOT NULL DEFAULT now(),
    created_by      varchar(100),
    voided_at       timestamp,
    voided_by       varchar(100)
);
CREATE INDEX idx_bank_transactions_tenant ON bank_transactions (tenant_id, txn_date DESC);

CREATE TABLE bank_transaction_lines (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           bigint        NOT NULL,
    bank_transaction_id bigint        NOT NULL REFERENCES bank_transactions (id),
    account_code        varchar(10)   NOT NULL,
    description         varchar(500),
    net                 numeric(18,2) NOT NULL,
    tax_name            varchar(100),
    tax_rate            numeric(7,4),
    tax_amount          numeric(18,2) NOT NULL DEFAULT 0
);
CREATE INDEX idx_bank_transaction_lines_txn ON bank_transaction_lines (bank_transaction_id);

-- Statement files imported, and their lines
CREATE TABLE bank_statement_imports (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    bigint       NOT NULL,
    account_code varchar(10)  NOT NULL,
    file_name    varchar(255),
    lines        int          NOT NULL DEFAULT 0,
    duplicates   int          NOT NULL DEFAULT 0,
    created_at   timestamp    NOT NULL DEFAULT now(),
    created_by   varchar(100)
);

CREATE TABLE bank_statement_lines (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     bigint        NOT NULL,
    account_code  varchar(10)   NOT NULL,
    import_id     bigint        REFERENCES bank_statement_imports (id),
    line_date     date          NOT NULL,
    amount        numeric(18,2) NOT NULL,          -- money in positive, money out negative
    payee         varchar(255),
    reference     varchar(255),
    description   varchar(500),
    balance       numeric(18,2),                   -- the statement's running balance, when the file has it
    fingerprint   varchar(64)   NOT NULL,          -- date + amount + payee + reference + description: duplicates skipped
    status        varchar(12)   NOT NULL DEFAULT 'UNRECONCILED',   -- UNRECONCILED, RECONCILED
    reconciled_at timestamp,
    reconciled_by varchar(100),
    created_at    timestamp     NOT NULL DEFAULT now()
);
CREATE INDEX idx_bank_statement_lines_account ON bank_statement_lines (tenant_id, account_code, status, line_date);
CREATE INDEX idx_bank_statement_lines_fingerprint ON bank_statement_lines (tenant_id, account_code, fingerprint);

-- What each statement line was reconciled with: ledger sources (PAY:12, CC:3, BT:7, MJ:2 …), each at most once per
-- bank account (a transfer is matched on both of its accounts)
CREATE TABLE bank_matches (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         bigint        NOT NULL,
    statement_line_id bigint        NOT NULL REFERENCES bank_statement_lines (id) ON DELETE CASCADE,
    account_code      varchar(10)   NOT NULL,
    source_key        varchar(120)  NOT NULL,
    amount            numeric(18,2) NOT NULL
);
CREATE UNIQUE INDEX uk_bank_matches_source ON bank_matches (tenant_id, source_key, lower(account_code));
CREATE INDEX idx_bank_matches_line ON bank_matches (statement_line_id);
