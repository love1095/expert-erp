-- Phase K1: the ERP's own accounting, like Xero: chart of accounts, a general ledger posted from every document,
-- manual journals, conversion (opening) balances.

-- Chart of accounts (Xero's account types; class derived from the type)
CREATE TABLE ledger_accounts (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   bigint       NOT NULL,
    code        varchar(10)  NOT NULL,
    name        varchar(150) NOT NULL,
    type        varchar(20)  NOT NULL,   -- BANK, CURRENT, FIXED, INVENTORY, NONCURRENT, PREPAYMENT, CURRLIAB, LIABILITY, TERMLIAB,
                                         -- EQUITY, REVENUE, SALES, OTHERINCOME, DIRECTCOSTS, EXPENSE, OVERHEADS, DEPRECIATN
    tax_type    varchar(100),            -- default VAT rate for the account (Xero's Tax Code)
    description varchar(500),
    archived    boolean      NOT NULL DEFAULT false,
    created_at  timestamp    NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_ledger_accounts_code ON ledger_accounts (tenant_id, lower(code));

-- Journals: never edited; a change to a document posts a reversal and a new journal
CREATE TABLE journals (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    bigint       NOT NULL,
    number       bigint       NOT NULL,                -- Xero's journal number, per organisation
    journal_date date         NOT NULL,
    source_type  varchar(20)  NOT NULL,                -- INVOICE, CREDIT_NOTE, BILL, SUPPLIER_CREDIT, PAYMENT, CREDIT, STOCK, MANUAL, OPENING
    source_key   varchar(120) NOT NULL,                -- e.g. DOC:12, PAY:40, MJ:3, OPENING
    reference    varchar(255),                         -- document number
    narration    varchar(500) NOT NULL,
    reversal     boolean      NOT NULL DEFAULT false,  -- reverses what was posted before for the same source
    created_at   timestamp    NOT NULL DEFAULT now(),
    created_by   varchar(100)
);
CREATE UNIQUE INDEX uk_journals_number ON journals (tenant_id, number);
CREATE INDEX idx_journals_source ON journals (tenant_id, source_key);
CREATE INDEX idx_journals_date ON journals (tenant_id, journal_date);

CREATE TABLE journal_lines (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    bigint        NOT NULL,
    journal_id   bigint        NOT NULL REFERENCES journals (id),
    account_code varchar(10)   NOT NULL,
    description  varchar(500),
    contact      varchar(255),
    -- Debit positive, credit negative
    amount       numeric(18,2) NOT NULL,
    tax_name     varchar(100),
    tax_amount   numeric(18,2)
);
CREATE INDEX idx_journal_lines_journal ON journal_lines (journal_id);
CREATE INDEX idx_journal_lines_account ON journal_lines (tenant_id, account_code);

-- Manual journals (Xero: Accounting → Manual journals): draft, posted, voided
CREATE TABLE manual_journals (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    bigint       NOT NULL,
    journal_date date         NOT NULL,
    narration    varchar(500) NOT NULL,
    status       varchar(10)  NOT NULL DEFAULT 'DRAFT',   -- DRAFT, POSTED, VOIDED
    created_at   timestamp    NOT NULL DEFAULT now(),
    created_by   varchar(100),
    posted_at    timestamp,
    voided_at    timestamp,
    voided_by    varchar(100)
);
CREATE INDEX idx_manual_journals_tenant ON manual_journals (tenant_id, journal_date DESC);

CREATE TABLE manual_journal_lines (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         bigint        NOT NULL,
    manual_journal_id bigint        NOT NULL REFERENCES manual_journals (id) ON DELETE CASCADE,
    line_no           int           NOT NULL,
    account_code      varchar(10)   NOT NULL,
    description       varchar(500),
    amount            numeric(18,2) NOT NULL    -- debit positive, credit negative
);

-- Conversion balances (Xero: Advanced → Conversion balances): the balances on the day before the conversion date
CREATE TABLE ledger_opening_balances (
    tenant_id    bigint        NOT NULL,
    account_code varchar(10)   NOT NULL,
    amount       numeric(18,2) NOT NULL,       -- debit positive, credit negative
    PRIMARY KEY (tenant_id, account_code)
);

