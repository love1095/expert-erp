-- Phase O: shipments booked with a courier (fake until the owner names the couriers): service, price, tracking, label

CREATE TABLE courier_shipments (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        bigint         NOT NULL,
    sale_order_id    bigint         NOT NULL REFERENCES sale_orders (id),
    mode             varchar(10)    NOT NULL,             -- fake / live: which courier client booked it
    carrier          varchar(100)   NOT NULL,
    service_code     varchar(50)    NOT NULL,
    service_name     varchar(150)   NOT NULL,
    price            numeric(18,2),
    consignment_id   varchar(100)   NOT NULL,
    tracking_number  varchar(100),
    tracking_url     varchar(500),
    label            bytea,
    parcels          int            NOT NULL,
    status           varchar(12)    NOT NULL DEFAULT 'BOOKED',   -- BOOKED, SHIPPED, DELIVERED, CANCELLED
    tracking_status  varchar(20),
    tracking_text    varchar(255),
    tracked_at       timestamp(6),
    fulfilment_id    bigint,
    created_at       timestamp(6)   NOT NULL DEFAULT now(),
    created_by       varchar(100),
    cancelled_at     timestamp(6),
    cancelled_by     varchar(100)
);
CREATE INDEX idx_courier_shipments_order ON courier_shipments (tenant_id, sale_order_id);

-- The cartons a booking covers (cancelled: freed again)
ALTER TABLE packages ADD COLUMN courier_shipment_id bigint REFERENCES courier_shipments (id);

-- The tracking link goes with the shipment (to Shopify, to the customer)
ALTER TABLE fulfilments ADD COLUMN tracking_url varchar(500);
