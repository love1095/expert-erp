-- Phase 7.4 (F): refunds made in Shopify. Each one is kept on its ERP order to be reviewed (business-rules.md §5):
-- a person makes the credit note (and restocks what came back) or cancels the unshipped quantities, or dismisses it.
CREATE TABLE shopify_refunds (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      bigint        NOT NULL,
    sale_order_id  bigint        NOT NULL REFERENCES sale_orders (id),
    refund_id      varchar(100)  NOT NULL,
    refunded_at    timestamp(6),
    -- Money given back in Shopify (VAT included); other_amount = beyond the items (shipping, goodwill)
    amount         numeric(18,2) NOT NULL,
    other_amount   numeric(18,2) NOT NULL DEFAULT 0,
    note           text,
    -- [{lineItemId, saleOrderLineId, sku, title, quantity, amount, restockType}]
    lines          text          NOT NULL,
    status         varchar(20)   NOT NULL DEFAULT 'TO_REVIEW',
    -- What the review did, e.g. "Credit note CR-12 (2 restocked)"
    outcome        text,
    reviewed_by    varchar(100),
    reviewed_at    timestamp(6),
    created_at     timestamp(6)  NOT NULL DEFAULT now(),
    CONSTRAINT uk_shopify_refunds_refund UNIQUE (tenant_id, refund_id),
    CONSTRAINT shopify_refunds_status_check CHECK (status IN ('TO_REVIEW', 'DONE', 'DISMISSED'))
);
CREATE INDEX idx_shopify_refunds_order ON shopify_refunds (sale_order_id);
CREATE INDEX idx_shopify_refunds_to_review ON shopify_refunds (tenant_id) WHERE status = 'TO_REVIEW';

-- Money Shopify paid back to the customer
ALTER TABLE payments DROP CONSTRAINT IF EXISTS payments_method_check;
ALTER TABLE payments ADD CONSTRAINT payments_method_check CHECK (method IN ('CASH', 'BANK', 'STRIPE', 'CREDIT_NOTE', 'SHOPIFY'));
