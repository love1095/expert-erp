-- Phase N5: stock adjustments with reasons and approval over a set value, and stock takes (full / partial)

ALTER TABLE stock_movements ADD COLUMN reason_code varchar(20);   -- DAMAGE, WRITE_OFF, SAMPLE, FOUND, THEFT, COUNT, OTHER

CREATE TABLE inventory_settings (
    tenant_id                   bigint PRIMARY KEY,
    adjustment_approval_value   numeric(18,2),        -- adjustments worth more than this wait for a manager; empty = none
    updated_at                  timestamp(6),
    updated_by                  varchar(100)
);

CREATE TABLE stock_adjustment_requests (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     bigint         NOT NULL,
    product_id    bigint         NOT NULL REFERENCES products (id),
    warehouse_id  bigint         NOT NULL REFERENCES warehouses (id),
    bin_id        bigint         REFERENCES warehouse_bins (id),
    quantity      numeric(18,4)  NOT NULL,            -- in positive, out negative
    reason_code   varchar(20)    NOT NULL,
    note          varchar(500),
    unit_cost     numeric(18,6),
    value         numeric(18,2)  NOT NULL,
    status        varchar(10)    NOT NULL,            -- PENDING, POSTED, REJECTED
    movement_id   bigint,
    requested_by  varchar(100),
    requested_at  timestamp(6)   NOT NULL DEFAULT now(),
    decided_by    varchar(100),
    decided_at    timestamp(6),
    decision_note varchar(500)
);
CREATE INDEX idx_stock_adjustment_requests ON stock_adjustment_requests (tenant_id, status, requested_at DESC);

CREATE TABLE stock_takes (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     bigint        NOT NULL,
    warehouse_id  bigint        NOT NULL REFERENCES warehouses (id),
    scope         varchar(10)   NOT NULL,              -- FULL, PARTIAL
    note          varchar(500),
    status        varchar(10)   NOT NULL DEFAULT 'COUNTING',   -- COUNTING, POSTED, CANCELLED
    created_at    timestamp(6)  NOT NULL DEFAULT now(),
    created_by    varchar(100),
    posted_at     timestamp(6),
    posted_by     varchar(100)
);
CREATE INDEX idx_stock_takes_tenant ON stock_takes (tenant_id, created_at DESC);

CREATE TABLE stock_take_lines (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      bigint         NOT NULL,
    stock_take_id  bigint         NOT NULL REFERENCES stock_takes (id) ON DELETE CASCADE,
    product_id     bigint         NOT NULL REFERENCES products (id),
    bin_id         bigint         REFERENCES warehouse_bins (id),   -- none: unbinned stock
    expected       numeric(18,4)  NOT NULL,          -- frozen when the stock take started
    counted        numeric(18,4),                    -- empty: not counted
    unit_cost      numeric(18,6)
);
CREATE INDEX idx_stock_take_lines_take ON stock_take_lines (stock_take_id);
