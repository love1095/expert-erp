INSERT INTO price_tiers (tenant_id, number, name)
SELECT t.id, 2, CASE WHEN EXISTS (SELECT 1 FROM customers c WHERE c.tenant_id = t.id AND lower(c.price_tier) = 'contract')
                     THEN 'Contract' ELSE 'Trade' END FROM tenants t;

-- Contract prices: one customer, one SKU, a price for a period (no end date = until changed)
CREATE TABLE customer_prices (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    bigint        NOT NULL,
    customer_id  bigint        NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    product_id   bigint        NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    unit_price   numeric(18,4) NOT NULL CHECK (unit_price >= 0),
    valid_from   date          NOT NULL,
    valid_to     date,
    note         varchar(255),
    created_by   varchar(100)  NOT NULL,
    created_at   timestamp(6)  NOT NULL,
    CONSTRAINT customer_prices_period_check CHECK (valid_to IS NULL OR valid_to >= valid_from)
);
CREATE INDEX idx_customer_prices_customer_product ON customer_prices (customer_id, product_id);

