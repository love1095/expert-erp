-- Phase G1 (spec §5): price tiers and contract prices. Which price an order line gets when none is typed:
-- the customer's contract price for the SKU valid on the order date, else the customer's tier, else tier 1 (Retail).

-- Tiers per organisation, numbered like Cin7's PriceTier1..10. A tier prices from the product's own price for
-- that tier (tiers 1-4 are kept on products, from Cin7's file), or, with a discount, as a percentage off tier 1.
CREATE TABLE price_tiers (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        bigint       NOT NULL,
    number           smallint     NOT NULL CHECK (number BETWEEN 1 AND 10),
    name             varchar(100) NOT NULL,
    discount_percent numeric(5,2) CHECK (discount_percent > 0 AND discount_percent < 100),
    CONSTRAINT uk_price_tiers_number UNIQUE (tenant_id, number),
    -- Tiers 5-10 have no product prices: they must be a percentage
    CONSTRAINT price_tiers_fixed_check CHECK (number <= 4 OR discount_percent IS NOT NULL)
);
CREATE UNIQUE INDEX uk_price_tiers_name ON price_tiers (tenant_id, lower(name));

-- Every organisation gets 1 Retail and 2 Contract (the names its Cin7 customers use) or Trade
INSERT INTO price_tiers (tenant_id, number, name)
