-- Phase N1: bins in each warehouse, a default bin per product, and stock per bin (spec §4).
-- Bin stock is a ledger of its own beside the stock movements: it never changes a warehouse's stock, only says where
-- in the warehouse it is; what is in no bin is the warehouse's stock less what the bins hold.

CREATE TABLE warehouse_bins (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     bigint        NOT NULL,
    warehouse_id  bigint        NOT NULL REFERENCES warehouses (id),
    code          varchar(60)   NOT NULL,          -- e.g. A-01-03
    walk_order    int           NOT NULL DEFAULT 0, -- the order a picker walks the bins
    active        boolean       NOT NULL DEFAULT true,
    created_at    timestamp(6)  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_warehouse_bins_code ON warehouse_bins (tenant_id, warehouse_id, lower(code));

CREATE TABLE product_bins (
    tenant_id     bigint NOT NULL,
    product_id    bigint NOT NULL REFERENCES products (id),
    warehouse_id  bigint NOT NULL REFERENCES warehouses (id),
    bin_id        bigint NOT NULL REFERENCES warehouse_bins (id),
    PRIMARY KEY (tenant_id, product_id, warehouse_id)
);

CREATE TABLE bin_movements (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     bigint         NOT NULL,
    product_id    bigint         NOT NULL REFERENCES products (id),
    warehouse_id  bigint         NOT NULL REFERENCES warehouses (id),
    bin_id        bigint         NOT NULL REFERENCES warehouse_bins (id),
    quantity      numeric(18,4)  NOT NULL,         -- into the bin positive, out negative
    reason        varchar(20)    NOT NULL,         -- RECEIVED, MOVED, PICKED, UNPICKED, LEFT, OPENING, COUNT
    reference     varchar(255),
    created_at    timestamp(6)   NOT NULL DEFAULT now(),
    created_by    varchar(100)
);
CREATE INDEX idx_bin_movements_stock ON bin_movements (tenant_id, product_id, warehouse_id, bin_id);
CREATE INDEX idx_bin_movements_bin ON bin_movements (tenant_id, bin_id);
