-- Phase D5: documents (docs/phase-d-sales.md). The organisation's details printed on quotes, orders, invoices, credit
-- notes and purchase orders: who we are, how to pay us, the logo. One row per organisation, made when first saved.
CREATE TABLE company_details (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         bigint       NOT NULL UNIQUE,
    legal_name        varchar(255),
    address           text,
    phone             varchar(100),
    email             varchar(255),
    website           varchar(255),
    vat_number        varchar(50),
    company_number    varchar(50),
    -- Printed on invoices: account name, sort code, account number...
    bank_details      text,
    -- Printed at the foot of every document (e.g. terms of sale)
    document_footer   text,
    logo              bytea,
    logo_content_type varchar(50),
    updated_at        timestamp(6) NOT NULL
);
