-- Phase N2 / N3: pick lists (one order or a wave of orders, in bin walk order), cartons packed, shipped from cartons

CREATE TABLE pick_lists (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     bigint        NOT NULL,
    warehouse_id  bigint        NOT NULL REFERENCES warehouses (id),
    status        varchar(10)   NOT NULL DEFAULT 'OPEN',   -- OPEN, PICKED, CANCELLED
    created_at    timestamp(6)  NOT NULL DEFAULT now(),
    created_by    varchar(100),
    picked_at     timestamp(6),
    picked_by     varchar(100)
);
CREATE INDEX idx_pick_lists_tenant ON pick_lists (tenant_id, status, created_at DESC);

CREATE TABLE pick_list_lines (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           bigint         NOT NULL,
    pick_list_id        bigint         NOT NULL REFERENCES pick_lists (id) ON DELETE CASCADE,
    sale_order_id       bigint         NOT NULL REFERENCES sale_orders (id),
    sale_order_line_id  bigint         NOT NULL REFERENCES sale_order_lines (id),
    product_id          bigint         NOT NULL REFERENCES products (id),
    bin_id              bigint         REFERENCES warehouse_bins (id),   -- none: unbinned stock
    walk_order          int            NOT NULL DEFAULT 2147483647,
    quantity            numeric(18,4)  NOT NULL,
    picked              numeric(18,4)  NOT NULL DEFAULT 0
);
CREATE INDEX idx_pick_list_lines_list ON pick_list_lines (pick_list_id);
CREATE INDEX idx_pick_list_lines_order ON pick_list_lines (tenant_id, sale_order_id);

CREATE TABLE packages (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      bigint         NOT NULL,
    sale_order_id  bigint         NOT NULL REFERENCES sale_orders (id),
    number         int            NOT NULL,             -- Package # within the order (Cin7)
    weight_kg      numeric(10,3),
    length_cm      numeric(10,1),
    width_cm       numeric(10,1),
    height_cm      numeric(10,1),
    status         varchar(10)    NOT NULL DEFAULT 'PACKED',   -- PACKED, SHIPPED
    fulfilment_id  bigint,
    created_at     timestamp(6)   NOT NULL DEFAULT now(),
    created_by     varchar(100)
);
CREATE INDEX idx_packages_order ON packages (tenant_id, sale_order_id);

CREATE TABLE package_lines (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           bigint         NOT NULL,
    package_id          bigint         NOT NULL REFERENCES packages (id) ON DELETE CASCADE,
    sale_order_line_id  bigint         NOT NULL REFERENCES sale_order_lines (id),
    quantity            numeric(18,4)  NOT NULL
);
CREATE INDEX idx_package_lines_package ON package_lines (package_id);
