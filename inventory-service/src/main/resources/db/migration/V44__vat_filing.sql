-- Phase K4: VAT returns filed (like Xero's VAT returns list) and the Making Tax Digital link to HMRC

-- A return as filed: the nine boxes kept as they were sent, and HMRC's receipt
CREATE TABLE vat_returns (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           bigint        NOT NULL,
    period_key          varchar(10),                 -- HMRC's key for the period (MTD), e.g. 24A1
    period_from         date          NOT NULL,
    period_to           date          NOT NULL,
    due_date            date,
    box1 numeric(18,2) NOT NULL, box2 numeric(18,2) NOT NULL, box3 numeric(18,2) NOT NULL, box4 numeric(18,2) NOT NULL,
    box5 numeric(18,2) NOT NULL, box6 numeric(18,0) NOT NULL, box7 numeric(18,0) NOT NULL, box8 numeric(18,0) NOT NULL,
    box9 numeric(18,0) NOT NULL,
    how                 varchar(10)   NOT NULL,       -- MTD (sent from here) or MANUAL (filed elsewhere, recorded here)
    filed_at            timestamp     NOT NULL DEFAULT now(),
    filed_by            varchar(100),
    processing_date     timestamp,                    -- HMRC's receipt
    form_bundle_number  varchar(20),
    payment_indicator   varchar(10),
    charge_ref_number   varchar(30),
    note                varchar(500)
);
CREATE UNIQUE INDEX uk_vat_returns_period ON vat_returns (tenant_id, period_from, period_to);

-- One HMRC connection per organisation: its VAT number and the OAuth tokens (encrypted)
CREATE TABLE hmrc_connections (
    tenant_id       bigint       PRIMARY KEY,
    vrn             varchar(12),
    access_token    varchar(2000),
    refresh_token   varchar(2000),
    expires_at      timestamp,
    oauth_state     varchar(64),
    connected_at    timestamp,
    connected_by    varchar(100)
);
